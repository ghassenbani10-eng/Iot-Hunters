"""Build a Markdown summary of the scenario results.

    ros2 run tunibot_delivery make_test_report <results_dir> [<output.md>]

Reads <results_dir>/tc*.json (written by scenario_runner) and writes a results
table + per-scenario details (default output: <results_dir>/TEST_RESULTS.md).
"""
import glob
import json
import os
import sys


def fmt(v):
    if v is None:
        return '-'
    if isinstance(v, float):
        return '%.2f' % v
    return str(v)


def main():
    res_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/tunibot_test_results')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(res_dir, 'TEST_RESULTS.md')
    results = []
    for p in sorted(glob.glob(os.path.join(res_dir, 'tc*.json'))):
        if p.endswith('_events.json'):
            continue
        with open(p) as f:
            results.append(json.load(f))
    lines = ['# TuniBot Phase 2 - automated test results', '',
             'Generated by `make_test_report` from `scenario_runner` outputs. Ground truth from Gazebo.', '',
             '| ID | Scenario | Result | Duration (s) | Min robot-person clearance (m) | Contacts | Min SoC (%) | Path (m) |',
             '|---|---|---|---|---|---|---|---|']
    for r in results:
        lines.append('| %s | %s | %s | %s | %s | %d | %s | %s |' % (
            r['scenario'].upper(), r.get('title', ''), 'PASS' if r.get('passed') else '**FAIL**',
            fmt(r.get('duration_s')), fmt(r.get('min_clearance_m')), len(r.get('contacts', [])),
            fmt(r.get('min_soc')), fmt(r.get('path_length_m'))))
    passed = sum(1 for r in results if r.get('passed'))
    lines += ['', '**%d / %d scenarios passed.**' % (passed, len(results)), '']
    for r in results:
        sid = r['scenario']
        lines += ['## %s - %s' % (sid.upper(), r.get('title', '')), '',
                  '*%s*' % r.get('description', ''), '',
                  '- **Pass criteria:** %s' % r.get('criteria', '-'),
                  '- **Result:** %s' % ('PASS' if r.get('passed') else 'FAIL' + (
                      ' (%s)' % r.get('failure') if r.get('failure') else '')),
                  '- **Measured:** `%s`' % json.dumps(r.get('measured', {})),
                  '- **Min clearance to a person:** %s m%s' % (
                      fmt(r.get('min_clearance_m')),
                      ' (t=%ss, %s, robot state %s)' % (r['min_clearance_at']['t'], r['min_clearance_at']['person'],
                                                       r['min_clearance_at']['state'])
                      if r.get('min_clearance_at') else ''),
                  '- **Contacts (bumper):** %d' % len(r.get('contacts', [])),
                  '- **Battery:** min %s %%, final %s %%, learned consumption %s Wh/m' % (
                      fmt(r.get('min_soc')), fmt(r.get('final_soc')), fmt(r.get('learned_wh_per_m'))),
                  '- **Orders:** %s' % ', '.join('#%s %s -> %s' % (o['id'], o['table'], o['status'])
                                                for o in r.get('orders', [])),
                  '']
        if r.get('error'):
            lines += ['- **Error:** `%s`' % r['error'], '']
        if os.path.exists(os.path.join(res_dir, sid + '.png')):
            lines += ['![%s](%s.png)' % (sid, sid), '']
        ev_path = os.path.join(res_dir, sid + '_events.json')
        if os.path.exists(ev_path):
            with open(ev_path) as f:
                evs = json.load(f)
            keep = [e for e in evs if e['kind'] not in ('order',)][:40]
            if keep:
                lines += ['<details><summary>Event log (%d events)</summary>' % len(evs), '', '```']
                lines += ['%7.1fs  %-9s %s' % (e.get('t_test', 0), e['kind'], e['text']) for e in keep]
                lines += ['```', '</details>', '']
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote %s (%d/%d passed)' % (out, passed, len(results)))


if __name__ == '__main__':
    main()
